"""Стоп-лист: запрещённые конструкции 6.5 и накопительный список связок.

    python tools/stoplist.py content/stage-0/*.md

Две проверки в одном проходе.

1. **6.5** — список запрещённых конструкций свода. Ищется только в прозе:
   листинги и код в обратных кавычках заглушаются, потому что 6.5 — про
   русский текст, а `!==` и `[Invoice!]!` — про синтаксис. Совпадения всё
   равно проверяются глазами: часть из них законна (термин «простой запрос»
   из Fetch Standard, существительное «данные» против местоимения «данный»).
2. **Связки** — накопительный стоп-лист авторских оборотов. Правило 11.3
   пункт 5 велит вести его вручную; сюда попадает то, что нашла приёмка
   (находка Ф-08) и то, что добавилось при письме. Один и тот же оборот в
   каждой теме подряд — признак шаблона, а не стиля.

Мера, по которой шаблон видно численно, — общие четырёхграммы прозы во всех
темах набора: печатается последней строкой. Служебный аппарат (шапка, состав
блоков, каркас этапа, описание схемы, скоропортящийся слой, маркеры
уверенности) из подсчёта вычитается: он предписан сводом и повторяться обязан.
"""

import re
import sys
from pathlib import Path

BANNED = [
    r"\bпрост[оаыейи]\w*\b", r"\bлегк[оаяийоеу]\w*\b", r"\bочевидн\w*",
    r"\bвсего лишь\b", r"\bэлементарн\w*", r"\bне составит труда\b",
    r"\bкак известно\b", r"\bвсем понятно\b",
    r"\bявляе\w+\b", r"\bявляют\w*\b", r"\bпредставля\w+ собой\b",
    r"\bимеет место\b", r"\bосуществля\w+", r"\bв целях\b",
    r"\bв связи с тем, что\b", r"\bуказанн\w+\b",
    r"\bсейчас\b", r"\bв настоящее время\b", r"\bна сегодняшний день\b",
    r"\bна сегодня\b",
    r"\bсовременн\w+", r"\bскоро\b", r"\bнедавно\b",
    # Навигация словом ищется в форме текста ссылки, а не в прозе: 6.5
    # запрещает «[здесь]», «[по ссылке]», «[читать далее]» как подпись под
    # адресом, и то же различение уже сделано в правиле Vale L-NAV
    # (`NavLink.yml`, `scope: raw`). Бесскобочный шаблон помечал законное
    # «переходит по ссылке из письма» в теме cookies — язык, а не навигацию
    # (сужено 2026-08-23).
    r"\[(?:здесь|тут|по ссылке|читать далее|подробнее|ссылка)\]\(",
    r"\bмощн\w+", r"\bудобн\w+", r"\bэффективн\w+", r"\bгибк\w+",
    r"\bмы в этой статье\b", r"\bпрежде чем перейти к\b",
    r"\bстоит отметить, что\b", r"\bне секрет, что\b",
    r"!", r"\bВы\b",
]

# Накопительный стоп-лист связок. Дополнять, а не переписывать.
CONNECTIVES = [
    "Опасность", "Начнём с", "Где здесь граница доверия",
    "Ложные срабатывания", "различается минимально", "отличается минимально",
    "Границы применимости", "Распространённое представление", "Это неверно",
    "Одна подсказка:", "Критерий выполнения** наблюдаемый",
    "Лично не проверялось ничего", "Часто слышно",
    "Случай, который это ломает", "Чего это не закрывает", "Что это стоит",
    "Прежде чем открывать разбор",
]

SERVICE = [
    r"^\*\*AG-PROTO.*?\n\n", r"^Состав блоков — .*?\n\n",
    r"^Каркас этапа:.*?\n\n", r"^\*\*Скоропортящийся слой\.\*\*.*?\n\n",
    r"^\*\*Маркеры уверенности\.\*\*.*?(\n\n|\Z)",
    r"^\*\*Число источников\.\*\*.*?\n\n", r"^\*\*Описание схемы\.\*\*.*?\n\n",
    r"^\*\*Зачем это в работе AppSec-инженера\.\*\*",
]


def body(text: str) -> str:
    return re.sub(r"\A---\n.*?\n---\n", "", text, flags=re.S)


def mask_code(text: str) -> str:
    """Код заглушён пробелами: строки и столбцы на месте, слов в них нет.

    Правила 6.5 — про русскую прозу, а не про синтаксис. До этой заглушки
    восклицательный знак находился в `!==` листинга и в `[Invoice!]!` схемы
    GraphQL, и автор трижды приходил смотреть на законное место. Заглушать, а
    не вырезать, потому что номер строки в отчёте должен указывать туда же,
    куда смотрит автор в редакторе.
    """
    def blank(m: re.Match) -> str:
        return re.sub(r"[^\n]", " ", m.group(0))
    text = re.sub(r"^```.*?^```", blank, text, flags=re.S | re.M)
    text = re.sub(r"`[^`\n]+`", blank, text)
    return text


def prose_ngrams(text: str, n: int = 4) -> set[tuple[str, ...]]:
    t = body(text)
    t = re.sub(r"```.*?```", "", t, flags=re.S)
    t = re.sub(r"<details>.*?</details>", "", t, flags=re.S)
    t = re.sub(r"^## 14\..*\Z", "", t, flags=re.M | re.S)
    for pat in SERVICE:
        t = re.sub(pat, "", t, flags=re.M | re.S)
    words = re.findall(r"[А-Яа-яЁёA-Za-z]+", t.lower())
    return {tuple(words[i:i + n]) for i in range(len(words) - n + 1)}


def main(argv: list[str]) -> int:
    grams = []
    for name in argv:
        text = Path(name).read_text(encoding="utf-8")
        b = body(text)
        prose = mask_code(b)
        hits = []
        for pat in BANNED:
            flags = 0 if "Вы" in pat else re.I
            for m in re.finditer(pat, prose, flags):
                line = prose[:m.start()].count("\n") + 1
                hits.append(f"  6.5   строка ~{line}: {m.group(0)}")
        for phrase in CONNECTIVES:
            count = b.count(phrase)
            if count:
                hits.append(f"  СВЯЗКА x{count}: {phrase}")
        print(f"== {Path(name).name}")
        print("\n".join(hits) if hits else "  чисто")
        grams.append(prose_ngrams(text))
    if len(grams) > 1:
        common = set.intersection(*grams)
        print(f"\nОбщих четырёхграмм прозы во всех {len(grams)} темах "
              f"(без служебного аппарата): {len(common)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
