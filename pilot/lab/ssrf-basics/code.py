"""Витрина партнёрских товаров: карточка тянется по адресу из запроса.

Фрагмент сервиса, сведённый к одному вопросу: куда уходит запрос,
собранный из пользовательских данных. Сети нет, HTTP не поднимается —
транспорт изображает `net.py`, запрос представлен словарём.

Лаборатория гайдбука. Всё исполняется локально и применимо только к
этой лабе.

Задача: починить сборку исходящего запроса так, чтобы hack.py перестал
срабатывать, а tests.py продолжил проходить.
"""

import net

# Партнёры, чьи карточки витрина показывает по договору.
PARTNERS = ("partner.example", "cdn.example")


class Denied(Exception):
    """Отказ собрать исходящий запрос. Обработчик даёт 400."""


# УЯЗВИМО — демонстрация, не для продакшена.
# Адрес приходит из запроса и уходит в клиент без единой проверки.
def preview(request):
    """Показать карточку товара по адресу, который прислал клиент."""
    url = request["query"].get("url", "")
    if not url:
        raise Denied("адрес не указан")
    resp = net.get(url)
    return {"status": 200, "body": resp["body"], "fetched": resp["url"]}


def handle(url):
    """Единая точка входа лабы: собрать запрос и отдать обработчику."""
    try:
        return preview({"query": {"url": url}})
    except Denied as exc:
        return {"status": 400, "body": str(exc), "fetched": None}
    except net.NetworkError as exc:
        return {"status": 502, "body": str(exc), "fetched": None}
