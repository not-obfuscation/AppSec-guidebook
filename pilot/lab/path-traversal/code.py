"""Выдача документов клиенту по имени файла.

Служба отдаёт счета из базового каталога. Имя файла приходит от клиента, и
разработчик о выходе за каталог подумал: перед открытием стоит проверка, что
собранный путь начинается с базового каталога.

Проверка стоит не в том месте. Путь сверяется с базовым каталогом ДО того, как
из него убраны переходы вверх, — а операционная система разберёт их при
открытии. Строка `<base>/../service.env` начинается с базового каталога и
проверку проходит; файл при этом открывается снаружи.

Лаборатория гайдбука. Всё исполняется локально и применимо только к этой лабе.

Задача: закрыть выход за базовый каталог так, чтобы hack.py перестал доставать
файл снаружи, а tests.py продолжил проходить (подкаталоги и точки внутри
базового каталога остаются рабочими).
"""

import os
import os.path

import sandbox


def list_documents():
    """Имена документов, доступных клиенту."""
    base = str(sandbox.base())
    return sorted(
        name for name in os.listdir(base)
        if os.path.isfile(os.path.join(base, name))
    )


# УЯЗВИМО — демонстрация, не для продакшена.
def read_document(name):
    """Отдать документ по имени. Имя приходит от клиента."""
    base = str(sandbox.base())
    path = os.path.join(base, name)
    if not path.startswith(base):        # проверка ДО канонизации пути
        raise PermissionError("вне базового каталога")
    with open(path, encoding="utf-8") as f:
        return f.read()
