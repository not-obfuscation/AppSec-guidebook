"""Эксплойт лабы: инъекция команды ОС через подпись отчёта.

Проверяет одно свойство — разбирает ли оболочка присланную строку как
команду. Признак исполнения — результат арифметики, которого нет в самой
строке: если в выводе появилась строка RESULT=77, вторую команду кто-то
исполнил. Запускается локально, к сети не обращается, против чужих систем
неприменим.

Код возврата:
    0 — эксплойт НЕ сработал (лаба починена)
    1 — эксплойт сработал (лаба ещё уязвима)
"""

import sys

from labtarget import load

# Разделитель команд плюс арифметика: в выводе RESULT=77 появится, только
# если строку исполнила оболочка. При запуске без оболочки эти символы
# попадут в подпись буквально, и 77 нигде не посчитается.
PAYLOAD = "x; echo RESULT=$((7*11))"


def experiment_1_chain(lab):
    """Разделитель ; запускает вторую команду."""
    out = lab.make_label(PAYLOAD)
    executed = "RESULT=77" in out
    print(f"  опыт 1 — цепочка через ; : "
          f"{'ВТОРАЯ КОМАНДА ИСПОЛНЕНА (RESULT=77)' if executed else 'не исполнена'}")
    return executed


def experiment_2_control(lab):
    """Контроль: обычная подпись строится и возвращается."""
    out = lab.make_label("Q3")
    ok = "Отчёт:" in out and "Q3" in out
    print(f"  опыт 2 — контроль, обычная подпись: "
          f"{'работает' if ok else 'ПОЧИНКА СЛОМАЛА ПОДПИСЬ'}")
    return ok


def experiment_3_control_meta(lab):
    """Контроль: подпись с точкой с запятой печатается как текст."""
    out = lab.make_label("Q3; финал")
    ok = "Q3; финал" in out
    print(f"  опыт 3 — контроль, ; в подписи как текст: "
          f"{'работает' if ok else 'подпись потеряла символы'}")
    return ok


def main() -> int:
    name, lab = load()
    print(f"Цель: {name}")
    hit = experiment_1_chain(lab)
    controls = [experiment_2_control(lab), experiment_3_control_meta(lab)]
    print()
    if hit:
        print("ЭКСПЛОЙТ СРАБОТАЛ: подпись разобрана оболочкой как команда")
        return 1
    if not controls[0]:
        print("ЭКСПЛОЙТ НЕ СРАБОТАЛ, но контроль упал: подпись перестала "
              "строиться — это не починка")
        return 1
    print("эксплойт не сработал: метасимволы попали в подпись как текст, "
          "подпись строится")
    return 0


if __name__ == "__main__":
    sys.exit(main())
