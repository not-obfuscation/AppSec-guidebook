"""Диагностика витрины: подпись к отчёту через внешний инструмент.

Фрагмент админ-панели: она строит короткую подпись к отчёту, вызывая
внешнюю утилиту оформления. Здесь роль утилиты играет echo — команда
безопасная и есть везде, а механизм инъекции от выбора утилиты не
зависит. Команда собирается склейкой и запускается через оболочку
(shell=True). Это и есть дефект темы.

Всё исполняется локально, без сети и без Docker. Ничего вне каталога
лабы команда не трогает.

Лаборатория гайдбука. Применимо только к этой лабе.

Задача: запускать инструмент без оболочки и без склейки, передавая
подпись отдельным аргументом.
"""

import subprocess


# УЯЗВИМО — демонстрация, не для продакшена.
def make_label(name):
    """Собрать подпись к отчёту и вернуть вывод инструмента."""
    command = "echo Отчёт: " + name          # (1)
    result = subprocess.run(                  # (2)
        command, shell=True,
        capture_output=True, text=True)
    return result.stdout


def reset():
    """Состояния нет: команда чистая. Оставлено для единообразия лаб."""
    return None
